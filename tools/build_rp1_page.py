#!/usr/bin/env python3
"""build_rp1_page.py -- generate site/earth/rp1.html: the directory of active RP1 worlds
connected to their Fly.io-hosted counterparts.

Every world in site/earth/worlds.json is registered as an rp1.com space (enter.rp1.com
anchor at its real-Earth place); the Sneeze mount plan set (worldforge/out/<slug>/
sneeze-mount-plan.json) marks the mounted worlds. This page is the human-readable view of
GET https://worldforge-api.fly.dev/v2/rp1/connections (the machine-readable list lives on
the Fly app and is generated from the same sources, so the two cannot disagree).

    python3 tools/build_rp1_page.py          # writes site/earth/rp1.html
    python3 tools/build_rp1_page.py --check  # exit 1 if the page is behind its sources
"""
import html
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))
WORLDS = os.path.join(ROOT, "site", "earth", "worlds.json")
OUT = os.path.join(ROOT, "worldforge", "out")
PAGE = os.path.join(ROOT, "site", "earth", "rp1.html")
API = "https://worldforge-api.fly.dev"
BASE = "https://www.agifuturefoundation.org"


def esc(s):
    return html.escape(str(s), quote=True)


def main():
    check_only = "--check" in sys.argv
    worlds = json.load(open(WORLDS, encoding="utf-8"))
    mounted = {n for n in os.listdir(OUT)
               if os.path.isfile(os.path.join(OUT, n, "sneeze-mount-plan.json"))}

    rows_m, rows_p = [], []
    for w in worlds:
        slug = w["slug"]
        enter = f"https://enter.rp1.com?start_cid=553&lat={w['lat']}&lon={w['lon']}&rad=6371000"
        cells = [
            f'<a href="world.html?world={esc(slug)}">{esc(w["name"])}</a>',
            esc(w.get("place") or ""),
            f'<a href="{esc(enter)}">enter.rp1.com</a>',
            f'<a href="{API}/v2/rp1/worlds/{esc(slug)}">API</a>',
        ]
        if slug in mounted:
            cells += [
                f'<a href="{API}/v2/sneeze/plans/{esc(slug)}">plan</a>',
                f'<a href="{API}/v2/worlds/{esc(slug)}/preview.glb">GLB</a>',
            ]
            rows_m.append("<tr><td>" + "</td><td>".join(cells) + "</td></tr>")
        else:
            cells += ["<em>plan pending</em>", "&mdash;"]
            rows_p.append("<tr><td>" + "</td><td>".join(cells) + "</td></tr>")

    doc = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>RP1 worlds x Fly.io</title>
<meta name="description" content="Every active RP1 space connected to its Fly.io-hosted WorldForge world: enter.rp1.com anchors, Sneeze mount plans, preview GLBs and API links.">
<style>
:root{{--ink:#e9f1ef;--mut:#9fb1ad;--acc:#43c59e;--bg:#0b1214}}
*{{box-sizing:border-box}}body{{margin:0;background:var(--bg);color:var(--ink);font:14px/1.5 system-ui,-apple-system,Segoe UI,sans-serif}}
main{{max-width:1080px;margin:0 auto;padding:24px 16px 64px}}h1{{font-size:1.5rem;margin:.2em 0}}h2{{font-size:1.1rem;color:var(--acc);margin:28px 0 8px}}
p{{color:var(--mut)}}a{{color:var(--acc)}}table{{border-collapse:collapse;width:100%;font-size:.82rem}}
th,td{{text-align:left;padding:6px 8px;border-bottom:1px solid rgba(255,255,255,.08);vertical-align:top}}
th{{color:var(--mut);font-weight:600;position:sticky;top:0;background:var(--bg)}}
em{{color:var(--mut)}}.count{{color:var(--acc);font-weight:700}}
details{{margin:18px 0}}summary{{cursor:pointer;color:var(--acc);font-size:.95rem}}
</style></head><body><main>
<h1>RP1 worlds &times; Fly.io</h1>
<p><span class="count">{len(worlds)}</span> active RP1 spaces, each connected to its Fly.io-hosted world &middot;
machine-readable list: <a href="{API}/v2/rp1/connections">/v2/rp1/connections</a> &middot;
app: <a href="https://fly.io/apps/worldforge-api">worldforge-api</a> &middot;
<a href="index.html">all worlds</a></p>
<h2>Mounted ({len(rows_m)}): full Sneeze engine payload on Fly</h2>
<table><tr><th>World</th><th>Place</th><th>RP1 space</th><th>Fly API</th><th>Sneeze plan</th><th>Preview GLB</th></tr>
{chr(10).join(rows_m)}</table>
<details><summary>Plan-pending ({len(rows_p)}): registered spaces, Sneeze mount plan awaits the worldforge build</summary>
<table><tr><th>World</th><th>Place</th><th>RP1 space</th><th>Fly API</th><th>Sneeze</th><th>GLB</th></tr>
{chr(10).join(rows_p)}</table></details>
<p style="margin-top:28px;font-size:.75rem">Generated by tools/build_rp1_page.py from site/earth/worlds.json + worldforge/out &middot; AGI Future Foundation PBC &middot; Powered by AGI Corp</p>
</main></body></html>
"""
    if check_only:
        current = open(PAGE, encoding="utf-8").read() if os.path.isfile(PAGE) else ""
        if current != doc:
            print("STALE: site/earth/rp1.html differs from its sources")
            sys.exit(1)
        print("OK: rp1.html current")
        return
    with open(PAGE, "w", encoding="utf-8") as f:
        f.write(doc)
    print(f"rp1.html: {len(worlds)} worlds ({len(rows_m)} mounted, {len(rows_p)} plan-pending), "
          f"{os.path.getsize(PAGE) // 1024} KB")


if __name__ == "__main__":
    main()
