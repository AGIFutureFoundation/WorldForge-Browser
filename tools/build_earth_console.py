#!/usr/bin/env python3
"""build_earth_console.py -- generate site/earth/console.html: the per-world ops console.

One row per world (all 544) with live status computed at build time:
geo dataset, preview video, team content (world/trades/robots/programs),
plus deep links to the world page, video and data. Groups by city, client-side
filter. Static HTML; rerun any time the videos/geo/team data change.

    python3 tools/build_earth_console.py
"""
import html
import json
import pathlib
import time

ROOT = pathlib.Path(__file__).resolve().parent.parent
EARTH = ROOT / 'site' / 'earth'


def status():
    """Only count files that are COMMITTED (git ls-files), so the generated page never
    references assets that a background capture/fetch may have written but not shipped."""
    import subprocess

    def tracked(pattern, cut):
        out = subprocess.run(['git', 'ls-files', '-z', pattern], cwd=EARTH,
                             capture_output=True, text=True).stdout.split('\0')
        return {pathlib.Path(p).name[:-cut] for p in out if p}

    geo = tracked('data/*.geo.json', 9)
    vids = tracked('videos/*.mp4', 4)
    team = tracked('team/world/*.json', 5)
    return geo, vids, team


def rows():
    worlds = json.loads((EARTH / 'worlds.json').read_text())
    geo, vids, team = status()
    out = []
    for w in worlds:
        s = w['slug']
        out.append({'slug': s, 'name': w.get('name', s), 'place': w.get('place', ''),
                    'biome': w.get('biome', ''), 'geo': s in geo, 'video': s in vids, 'team': s in team})
    return out, (len(geo), len(vids), len(team))


def chip(ok, label):
    cls = 'ok' if ok else 'no'
    mark = '&#10003;' if ok else '&middot;'
    return f'<span class="chip {cls}">{mark} {label}</span>'


def render():
    rs, (ng, nv, nt) = rows()
    trs = []
    for r in rs:
        links = (f'<a href="world.html?world={r["slug"]}">World</a>')
        if r['geo']:
            links += f' <a href="data/{r["slug"]}.geo.json">Data</a>'
        if r['video']:
            links += f' <a href="videos/{r["slug"]}.mp4">Video</a>'
        trs.append(
            f'<tr data-city="{html.escape(r["slug"].split("-")[0])}" '
            f'data-name="{html.escape((r["name"] + " " + r["place"] + " " + r["slug"]).lower())}">'
            f'<td><a href="world.html?world={r["slug"]}">{html.escape(r["name"])}</a>'
            f'<small>{html.escape(r["slug"])}</small></td>'
            f'<td>{html.escape(r["place"])}<small>{html.escape(r["biome"])}</small></td>'
            f'<td>{chip(r["geo"], "geo")}{chip(r["video"], "video")}{chip(r["team"], "content")}</td>'
            f'<td class="lnk">{links}</td></tr>')
    body = '\n'.join(trs)
    stamp = time.strftime('%Y-%m-%d %H:%M')
    total = len(rs)
    return f'''<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>WorldForge Earth — Worlds Console</title><style>{CSS}</style></head><body>
<header><h1>Earth Worlds <span>Console</span></h1>
<p>Every world with its live status: geo data, preview video, world content. Click a name to walk it.</p>
<div class="stats"><div><b>{total}</b><span>Worlds</span></div><div><b>{ng}</b><span>Geo</span></div>
<div><b>{nv}</b><span>Videos</span></div><div><b>{nt}</b><span>Content</span></div></div>
<div class="bar"><input id="q" placeholder="filter by name, city or slug..." autocomplete="off">
<span id="count"></span></div></header>
<main><table><thead><tr><th>World</th><th>Place</th><th>Status</th><th>Links</th></tr></thead>
<tbody id="tb">
{body}
</tbody></table></main>
<footer>Generated by tools/build_earth_console.py at {stamp} &middot; status chips are build-time facts, not live probes</footer>
<script>
const q=document.getElementById('q'),tb=document.getElementById('tb'),rows=[...tb.rows];
const upd=()=>{{let n=0;for(const r of rows){{const hit=!q.value||r.dataset.name.includes(q.value.toLowerCase());
r.style.display=hit?'':'none';if(hit)n++;}}document.getElementById('count').textContent=n+' worlds';}};
q.addEventListener('input',upd);upd();
</script></body></html>
'''


CSS = '''*{box-sizing:border-box;margin:0;padding:0}
body{background:#0a0f14;color:#e2e8f0;font:14px/1.45 system-ui,sans-serif}
a{color:#34d399;text-decoration:none}a:hover{color:#6ee7b7}
header{padding:32px 20px 20px;text-align:center;border-bottom:1px solid rgba(52,211,153,.2)}
header h1{font-size:1.8rem;margin-bottom:6px}header h1 span{color:#34d399}header p{color:#94a3b8;margin-bottom:12px}
.stats{display:flex;justify-content:center;gap:24px;padding:14px;flex-wrap:wrap}
.stats div{text-align:center}.stats b{display:block;font-size:1.4rem;color:#34d399}
.stats span{font-size:.7rem;color:#64748b;text-transform:uppercase}
.bar{display:flex;gap:12px;justify-content:center;align-items:center;padding:8px}
.bar input{background:#111827;border:1px solid rgba(52,211,153,.25);color:#e2e8f0;border-radius:6px;
padding:8px 12px;width:min(420px,80vw);font-size:.95rem}
.bar span{color:#64748b;font-size:.8rem}
main{max-width:1000px;margin:0 auto;padding:12px 16px 40px}
table{width:100%;border-collapse:collapse}th,td{text-align:left;padding:7px 10px;border-bottom:1px solid rgba(255,255,255,.06)}
th{color:#34d399;font-size:.72rem;text-transform:uppercase;letter-spacing:.05em}
td small{display:block;color:#64748b;font-size:.72rem}
td.lnk a{font-size:.85rem}
.chip{display:inline-block;font-size:.65rem;padding:1px 6px;border-radius:3px;margin-right:4px}
.chip.ok{background:rgba(52,211,153,.12);color:#34d399}.chip.no{background:rgba(148,163,184,.08);color:#64748b}
footer{padding:16px;color:#64748b;font-size:.75rem;text-align:center}'''


def main():
    (EARTH / 'console.html').write_text(render())
    print('wrote site/earth/console.html')


if __name__ == '__main__':
    main()
