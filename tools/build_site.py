def norm(base_dir, ref):
    """A page-relative reference -> a repository path, or None when it is external, a fragment or outside the repo."""
    ref = ref.strip()
    if not ref or ref.startswith(("#", "data:", "mailto:", "javascript:", "tel:")) or re.match(r"^[a-z][a-z0-9+.-]*:", ref, re.I) or ref.startswith("//"):
        return None
    ref = re.split(r"[?#]", ref)[0]
    if not ref or "'" in ref or "+" in ref or "{" in ref:
        return None
    p = os.path.normpath(os.path.join(base_dir, ref)) if not ref.startswith("/") else ref.lstrip("/")
    return None if p.startswith("..") else p.replace(os.sep, "/")


