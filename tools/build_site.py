def md_to_html(text):
    """A small, safe Markdown subset (headings, lists, paragraphs, code spans) for the overview pages."""
    out, para, lst = [], [], False

    def inline(s):
        s = html.escape(s)
        s = re.sub(r"`([^`]+)`", r"<code>\1</code>", s)
        s = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", s)
        return re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", lambda m: f'<a href="{m.group(2)}">{m.group(1)}</a>' if not m.group(2).lower().startswith("javascript:") else m.group(1), s)

    def flush():
        nonlocal para
        if para:
            out.append("<p>" + inline(" ".join(para)) + "</p>"); para = []
    for line in text.splitlines():
        if m := re.match(r"^(#{1,4})\s+(.*)$", line):
            flush(); out.append("</ul>" if lst else ""); lst = False
            out.append(f"<h{len(m.group(1))}>{inline(m.group(2))}</h{len(m.group(1))}>")
        elif m := re.match(r"^\s*[-*]\s+(.*)$", line):
            flush()
            if not lst:
                out.append("<ul>"); lst = True
            out.append(f"<li>{inline(m.group(1))}</li>")
        elif not line.strip():
            flush()
            if lst:
                out.append("</ul>"); lst = False
        else:
            para.append(line.strip())
    flush()
    if lst:
        out.append("</ul>")
    return "\n".join(x for x in out if x)


