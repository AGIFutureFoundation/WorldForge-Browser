def scan(files, generated):
    bad = []
    for p in files:
        if p.endswith((".html", ".json", ".vtt", ".md", ".txt", ".js", ".css")):
            t = open(os.path.join(ROOT, sizes({p: files[p]})[p][0]), encoding="utf-8", errors="replace").read()
            bad += [f"{p}: matches {rx.pattern[:24]}" for rx in SECRET_RX if rx.search(t)]
    for p, t in generated.items():
        bad += [f"{p}: matches {rx.pattern[:24]}" for rx in SECRET_RX if rx.search(t)]
    return bad


