def sizes(files):
    out = {}
    for p in files:
        src = p
        why = files[p]
        m = re.search(r"source (\S+)\)$", why)
        if m:
            src = m.group(1)
        out[p] = (src, os.path.getsize(os.path.join(ROOT, src)))
    return out


