def build(files, generated, summary, mapping):
    if os.path.isdir(DIST):
        if os.path.realpath(DIST) != os.path.realpath(os.path.join(HERE, "dist")):
            raise SystemExit("refusing to clear an unexpected dist path")
        shutil.rmtree(DIST)
    sz = sizes(files)
    for p, (src, _) in sz.items():
        dst = os.path.join(DIST, p)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copyfile(os.path.join(ROOT, src), dst)
    for p, text in generated.items():
        dst = os.path.join(DIST, p)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        with open(dst, "w", encoding="utf-8") as f:
            f.write(text)
    man = {"generated_by": "worldforge/site/build_site.py", "layout": "repository paths, copied byte-for-byte; nothing rewritten",
           "files": summary["files"] + 1, "bytes": summary["bytes"], "limits": {"per_file_MiB": 25, "max_files": MAX_FILES},
           "checks": {"over_25MiB": summary["over_25MiB"], "missing_required": summary["missing_required"], "ok": summary["ok"]},
           "substituted": [{"source": s, "served_at": t} for s, t in mapping if s != t],
           "contents": {p: {"bytes": s, "why": files[p]} for p, (_, s) in sorted(sz.items())}}
    with open(os.path.join(DIST, "site-manifest.json"), "w", encoding="utf-8") as f:
        json.dump(man, f, indent=1, sort_keys=True)
    # verify the copy
    bad = [p for p, (src, _) in sz.items() if sha_file(os.path.join(ROOT, src)) != sha_file(os.path.join(DIST, p))]
    n = sum(len(fs) for _, _, fs in os.walk(DIST))
    print(f"wrote {DIST} ({n} files); byte-identical copies: {'all' if not bad else f'{len(bad)} DIFFER'}")
    return not bad


def sha_file(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


