def header_rules():
    rules, cur = [], None
    for line in open(os.path.join(DIST, "_headers"), encoding="utf-8"):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if not line.startswith((" ", "\t")):
            cur = (re.compile("^" + re.escape(line.strip()).replace(r"\*", ".*") + "$"), []); rules.append(cur)
        else:
            k, v = line.strip().split(":", 1); cur[1].append((k.strip(), v.strip()))
    return rules


class PagesHandler(SimpleHTTPRequestHandler):
    """Serves dist/ the way Cloudflare Pages would for these files: the _headers rules applied, Content-Type from _headers
    (later rules override earlier ones for the same header), directory index.html."""
    rules = []

    def __init__(self, *a, **kw):
        super().__init__(*a, directory=DIST, **kw)

    def log_message(self, *a):
        pass

    def send_header(self, k, v):
        if k.lower() == "content-type" and getattr(self, "_ct", None):
            v = self._ct
        super().send_header(k, v)

    def end_headers(self):
        for k, v in getattr(self, "_extra", {}).items():
            if k.lower() != "content-type":
                super().send_header(k, v)
        super().end_headers()

    def send_head(self):
        path = self.path.split("?", 1)[0]
        extra = {}
        for rx, hs in self.rules:
            if rx.match(path):
                for k, v in hs:
                    extra[k] = v
        self._extra = extra
        self._ct = extra.get("Content-Type")
        return super().send_head()


def smoke():
    if not os.path.isdir(DIST):
        raise SystemExit("dist/ does not exist: run python3 worldforge/site/build_site.py first")
    PagesHandler.rules = header_rules()
    class Quiet(ThreadingHTTPServer):
        def handle_error(self, request, client_address):   # a client that stops reading early (partial GET) is not a failure
            pass
    srv = Quiet(("127.0.0.1", PORT), PagesHandler)
    th = threading.Thread(target=srv.serve_forever, daemon=True); th.start()
    base = f"http://127.0.0.1:{PORT}"
    man = json.load(open(os.path.join(DIST, "site-manifest.json"), encoding="utf-8"))
    glb = next(p for p in man["contents"] if p.startswith("my-fabric/worlds/models/") and p.endswith(".glb"))
    blockout = next(p for p in man["contents"] if re.match(r"worldforge/out/[^/]+/[^/]+\.glb$", p))
    mp4 = next((p for p in man["contents"] if p.endswith(".mp4")), None)
    vtt = next((p for p in man["contents"] if p.endswith(".vtt")), None)
    checks = [("/", "text/html", None), ("/worldforge/viewer.html?world=locator-x", "text/html", "WorldForge viewer"),
              ("/worldforge/out/index.json", "application/json", None), (f"/{glb}", "model/gltf-binary", "glTF"), (f"/{blockout}", "model/gltf-binary", "glTF"),
              ("/consoles/worldforge/", "text/html", None)]
    if mp4:
        checks.append((f"/{mp4}", "video/mp4", None))
    if vtt:
        checks.append((f"/{vtt}", "text/vtt", "WEBVTT"))
    results, ok = [], True
    try:
        for path, ct, needle in checks:
            req = urllib.request.Request(base + path, method="GET")
            with urllib.request.urlopen(req, timeout=20) as r:
                body = r.read(4096 if not path.endswith(".glb") else 12)
                got = r.headers.get("Content-Type", "")
                cors = r.headers.get("Access-Control-Allow-Origin")
                good = r.status == 200 and got.startswith(ct) and (needle is None or needle.encode() in body)
                if path.endswith(".glb"):
                    good = good and body[:4] == b"glTF" and cors == "*"
                results.append((path, r.status, got, cors, good)); ok &= good
        # every file in the manifest answers 200 to HEAD
        fails = []
        for p in man["contents"]:
            req = urllib.request.Request(base + "/" + p, method="HEAD")
            try:
                with urllib.request.urlopen(req, timeout=20) as r:
                    if r.status != 200:
                        fails.append(p)
            except Exception:
                fails.append(p)
        ok &= not fails
    finally:
        srv.shutdown()
    for path, st, ct, cors, good in results:
        print(f"{'ok  ' if good else 'FAIL'}  GET {path} -> {st} {ct}" + (f", CORS {cors}" if cors else ""))
    print(f"{'ok  ' if not fails else 'FAIL'}  HEAD on all {len(man['contents'])} shipped files -> 200" + "".join(f"\n        {p}" for p in fails[:10]))
    print(f"---- site smoke on 127.0.0.1:{PORT}: {'pass' if ok else 'FAIL'}")
    return ok


def main():
    if "--smoke" in sys.argv:
        sys.exit(0 if smoke() else 1)
    files, missing, notes, mapping = plan()
    generated = generated_files(files)
    summary = report(files, missing, notes, mapping, generated)
    if "--dry-run" in sys.argv:
        print(f"---- site dry run: {summary['files']} files, {summary['bytes'] / 1048576:.1f} MiB, {'within' if summary['ok'] else 'NOT within'} "
              f"Cloudflare Pages limits; nothing written")
        sys.exit(0 if summary["ok"] else 1)
    if not summary["ok"]:
        print("nothing written: fix the failures above"); sys.exit(1)
    good = build(files, generated, summary, mapping)
    print(f"---- site built: worldforge/site/dist, {summary['files'] + 1} files, {summary['bytes'] / 1048576:.1f} MiB")
    sys.exit(0 if good else 1)


